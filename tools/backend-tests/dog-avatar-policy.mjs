import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { PGlite } = require('@electric-sql/pglite');
const db = new PGlite();
const owner='00000000-0000-0000-0000-000000000001';
const other='00000000-0000-0000-0000-000000000002';
const dog='10000000-0000-0000-0000-000000000001';
const photo='avatar-20000000-0000-0000-0000-000000000001.jpg';
const path=`${owner}/dogs/${dog}/${photo}`;
await db.exec(`create role authenticated;
create schema auth; create schema storage;
create function auth.uid() returns uuid language sql stable as $$select current_setting('request.jwt.claim.sub',true)::uuid$$;
create function storage.foldername(text) returns text[] language sql immutable as $$select (string_to_array($1,'/'))[1:array_length(string_to_array($1,'/'),1)-1]$$;
create function storage.filename(text) returns text language sql immutable as $$select split_part($1,'/',-1)$$;
create table public.dogs(id uuid primary key,owner_id uuid,name text);
create table storage.objects(bucket_id text,name text,primary key(bucket_id,name));
insert into public.dogs values ('${dog}','${owner}','Ordinary dog name');
grant usage on schema public,auth,storage to authenticated;
grant select on public.dogs to authenticated;
grant select,insert,update,delete on storage.objects to authenticated;
alter table storage.objects enable row level security;
create policy "Avatar dog insert own dog path" on storage.objects for insert to authenticated
with check (exists(select 1 from public.dogs d where d.id::text=(storage.foldername(name))[3] and d.owner_id=auth.uid()));
create policy "Avatar dog read by owner" on storage.objects for select to authenticated using(false);
create policy "Avatar dog update own dog path" on storage.objects for update to authenticated using(false) with check(false);
create policy "Avatar dog delete own dog path" on storage.objects for delete to authenticated using(false);
set role authenticated; select set_config('request.jwt.claim.sub','${owner}',false);`);
await assert.rejects(db.exec(`insert into storage.objects values('dog-avatars','${path}')`),/row-level security/);
console.log('PASS reproduction: dog-name shadowing rejects an owned dog image');
await db.exec('reset role');
await db.exec(readFileSync(new URL('../../supabase/proposals/202610110012_dog_avatar_storage_fix.sql',import.meta.url),'utf8'));
await db.exec(`set role authenticated; insert into storage.objects values('dog-avatars','${path}')`);
assert.equal((await db.query('select * from storage.objects')).rows.length,1);
console.log('PASS own dog upload/read');
await db.exec(`update storage.objects set name='${path.replace(photo,'avatar-20000000-0000-0000-0000-000000000002.jpg')}'`);
assert.equal((await db.query('select * from storage.objects')).rows.length,1);
console.log('PASS own dog update');
await db.exec(`select set_config('request.jwt.claim.sub','${other}',false)`);
assert.equal((await db.query('select * from storage.objects')).rows.length,0);
await assert.rejects(db.exec(`insert into storage.objects values('dog-avatars','${path}')`),/row-level security/);
await assert.rejects(db.exec(`insert into storage.objects values('dog-avatars','${other}/dogs/${dog}/${photo}')`),/row-level security/);
await db.exec('delete from storage.objects');
console.log('PASS cross-account read/upload/delete isolation');
await db.exec(`select set_config('request.jwt.claim.sub','${owner}',false)`);
for (const invalid of [path.replace('.jpg','.png'),path.replace('/dogs/','/other/'),path.replace(dog,other),path+'/nested.jpg']) {
  await assert.rejects(db.query('insert into storage.objects values ($1,$2)',['dog-avatars',invalid]),/row-level security/);
}
await assert.rejects(db.query('insert into storage.objects values ($1,$2)',['profile-avatars',path]),/row-level security/);
console.log('PASS malformed paths, wrong bucket and missing dog denied');
assert.equal((await db.query('select * from storage.objects')).rows.length,1);
await db.exec('delete from storage.objects');
assert.equal((await db.query('select * from storage.objects')).rows.length,0);
console.log('PASS owned object delete; all policy regression groups passed');
await db.close();
